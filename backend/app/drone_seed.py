def _waypoints(points: list[dict], default_altitude: int = 120) -> list[dict]:
    result = []
    for point in points:
        result.append(
            {
                "lng": point["lng"],
                "lat": point["lat"],
                "altitude": point.get("altitude", default_altitude),
                "action": point.get("action", "拍照"),
                "name": point.get("name"),
            }
        )
    return result


